def load_inventory():
    """Load the generated application surface inventory."""
    if not APP_SURFACE.exists():
        raise AssertionError(
            f"Missing {APP_SURFACE.relative_to(REPO_ROOT)}. "
            "Run: python scripts/build_docs_inventory.py"
        )
    return yaml.safe_load(io.open(APP_SURFACE, encoding="utf-8"))


def load_docs_corpus():
    """Concatenate the text of every published documentation page."""
    seen = set()
    chunks = []

    for pattern in DOC_GLOBS:
        for path in DOCS_ROOT.glob(pattern):
            if not path.is_file() or path in seen:
                continue
            parts = set(path.relative_to(DOCS_ROOT).parts)
            if "_site" in parts or "fixes" in parts:
                continue
            seen.add(path)
            chunks.append(io.open(path, encoding="utf-8", errors="ignore").read())

    if not chunks:
        raise AssertionError("No documentation pages were found to scan.")

    return "\n".join(chunks)


def report_missing(label, missing, total, remediation):
    """Format a coverage failure message."""
    return (
        f"{label}: {len(missing)} of {total} are undocumented.\n"
        f"  Missing: {', '.join(sorted(missing)[:25])}"
        f"{' ...' if len(missing) > 25 else ''}\n"
        f"  {remediation}"
    )


def test_inventory_is_in_sync():
    """The generated inventory must match the current application."""
    print("Checking docs/_data/app_surface.yml is in sync with the application...")

    if not INVENTORY_SCRIPT.exists():
        print(f"  Skipped: {INVENTORY_SCRIPT.relative_to(REPO_ROOT)} not found.")
        return True

    result = subprocess.run(
        [sys.executable, str(INVENTORY_SCRIPT), "--check"],
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
    )

    if result.returncode != 0:
        print("Inventory is stale. Regenerate it with:")
        print("  python scripts/build_docs_inventory.py")
        print(result.stdout.strip())
        print(result.stderr.strip())
        return False

    print("  Inventory is current.")
    return True


def test_admin_group_coverage():
    """Every admin settings group must have a documentation page.

    Admin Settings was reworked from 18 flat tabs into a grouped information
    architecture of GROUP -> TAB -> SECTION, defined in admin_settings_nav.py.
    Documentation is organized one page per group, because several tabs carry
    only one or two settings sections and would make very thin pages.
    """
    print("Checking admin settings group documentation coverage...")

    inventory = load_inventory()
    groups = [group["id"] for group in inventory.get("admin_groups", [])]
    missing = [group for group in groups if not (DOCS_ROOT / "admin" / f"{group}.md").exists()]

    if missing:
        print(report_missing(
            "Admin settings groups", missing, len(groups),
            "Add a page at docs/admin/<group-id>.md for each missing group.",
        ))
        return False

    print(f"  All {len(groups)} admin settings groups are documented.")
    return True


def test_admin_tab_coverage():
    """Every admin settings tab must be documented on its group's page.

    Tabs are documented as headings within their group page rather than as
    separate pages, so each tab id must appear as a heading anchor. That keeps
    deep links to a specific tab working.
    """
    print("Checking admin settings tab documentation coverage...")

    inventory = load_inventory()
    tabs = inventory.get("admin_tabs", [])
    missing = []

    for tab in tabs:
        page = DOCS_ROOT / "admin" / f"{tab['group']}.md"
        if not page.exists():
            missing.append(f"{tab['id']} (group page {tab['group']}.md missing)")
            continue

        content = io.open(page, encoding="utf-8", errors="ignore").read()
        # Accept an explicit kramdown heading anchor or an existing HTML anchor.
        anchors = (
            "{#" + tab["id"] + "}",
            'id="' + tab["id"] + '"',
            "{: #" + tab["id"] + "}",
        )
        if not any(anchor in content for anchor in anchors):
            missing.append(f"{tab['id']} (no anchor in {tab['group']}.md)")

    if missing:
        print(report_missing(
            "Admin settings tabs", missing, len(tabs),
            "Give each tab a heading anchor on its group page, for example "
            "'## Redis & Caching {#redis-caching}'.",
        ))
        return False

    print(f"  All {len(tabs)} admin settings tabs are documented on their group pages.")
    return True


def test_action_coverage():
    """Every action plugin must be documented."""
    print("Checking action documentation coverage...")

    inventory = load_inventory()
    actions = [action["slug"] for action in inventory.get("actions", [])]
    corpus = load_docs_corpus()

    missing = []
    for slug in actions:
        page = DOCS_ROOT / "reference" / "actions" / f"{slug}.md"
        if page.exists():
            continue
        if slug in corpus:
            continue
        missing.append(slug)

    if missing:
        print(report_missing(
            "Actions", missing, len(actions),
            "Add a page at docs/reference/actions/<slug>.md for each missing action.",
        ))
        return False

    print(f"  All {len(actions)} actions are documented.")
    return True


def test_chat_control_coverage():
    """Every chat control must appear in the chat interface reference."""
    print("Checking chat control documentation coverage...")

    inventory = load_inventory()
    controls = [control["id"] for control in inventory.get("chat_controls", [])]
    corpus = load_docs_corpus()

    missing = [control for control in controls if control not in corpus]

    if missing:
        print(report_missing(
            "Chat controls", missing, len(controls),
            "Document each control in docs/reference/chat-controls.md.",
        ))
        return False

    print(f"  All {len(controls)} chat controls are documented.")
    return True


def test_capability_coverage():
    """Every user-facing capability toggle must be documented."""
    print("Checking capability toggle documentation coverage...")

    inventory = load_inventory()
    capabilities = [capability["key"] for capability in inventory.get("capabilities", [])]
    corpus = load_docs_corpus()

    missing = [
        key for key in capabilities
        if key not in corpus and key not in CAPABILITY_EXEMPTIONS
    ]

    if missing:
        print(report_missing(
            "Capability toggles", missing, len(capabilities),
            "Document each toggle on the relevant docs/admin/<tab>.md page, or add a "
            "justified entry to CAPABILITY_EXEMPTIONS in this test if it is an "
            "internal-only flag.",
        ))
        return False

    documented = len(capabilities) - len(CAPABILITY_EXEMPTIONS)
    print(f"  {documented} user-facing capability toggles are documented "
          f"({len(CAPABILITY_EXEMPTIONS)} internal flags exempt).")
    return True


def test_exemptions_are_still_real():
    """Exempted toggles must still exist, so the list cannot rot."""
    print("Checking capability exemption list has no stale entries...")

    inventory = load_inventory()
    capabilities = {capability["key"] for capability in inventory.get("capabilities", [])}
    stale = sorted(key for key in CAPABILITY_EXEMPTIONS if key not in capabilities)

    if stale:
        print(f"  These exemptions reference toggles that no longer exist: {', '.join(stale)}")
        print("  Remove them from CAPABILITY_EXEMPTIONS in this test.")
        return False

    print(f"  All {len(CAPABILITY_EXEMPTIONS)} exemptions reference real toggles.")
    return True


if __name__ == "__main__":
    assert_app_version_at_least("0.260.020")

    tests = [
        test_inventory_is_in_sync,
        test_admin_group_coverage,
        test_admin_tab_coverage,
        test_action_coverage,
        test_chat_control_coverage,
        test_capability_coverage,
        test_exemptions_are_still_real,
    ]

    results = []
    for test in tests:
        print(f"\nRunning {test.__name__}...")
        try:
            results.append(test())
        except Exception as error:  # noqa: BLE001 - report and continue
            print(f"Test raised an exception: {error}")
            import traceback
            traceback.print_exc()
            results.append(False)

    print(f"\nResults: {sum(1 for r in results if r)}/{len(results)} checks passed")
    sys.exit(0 if all(results) else 1)
