#!/usr/bin/env python3
"""
Functional test for documentation coverage of the application surface.
Version: 0.260.020
Implemented in: 0.250.230

This test ensures that every user-facing capability of SimpleChat has
documentation on the docs site. It is the mechanism that keeps documentation
current as pull requests land: adding a new settings toggle, admin settings
tab, action plugin, or chat control without documenting it fails this test.

The application surface is captured in docs/_data/app_surface.yml, which is
generated by scripts/build_docs_inventory.py. This test also verifies that
inventory is still in sync with the application, so a stale inventory cannot be
used to hide missing documentation.
"""

import io
import os
import re
import subprocess
import sys
from pathlib import Path

sys.path.append(os.path.dirname(os.path.abspath(__file__)))

import yaml

from test_support.versioning import assert_app_version_at_least

REPO_ROOT = Path(__file__).resolve().parents[1]
DOCS_ROOT = REPO_ROOT / "docs"
APP_SURFACE = DOCS_ROOT / "_data" / "app_surface.yml"
INVENTORY_SCRIPT = REPO_ROOT / "scripts" / "build_docs_inventory.py"

# Documentation folders that count as coverage. Engineering notes under
# docs/explanation/features and docs/explanation/fixes are deliberately excluded
# because they are internal change records, not user documentation, and they are
# excluded from the published site.
