# build_ui_route_map.py

"""Build the V2 TypeScript copy of the classic to V2 page route map, and keep its document in step.

``application/single_app/ui_route_map.json`` is the source of truth for which V2 route
replaces each classic page route. The V2 application needs the same data (to offer "open this
page in classic" and, later, to translate links in the browser), so this script renders it as
``application/v2_ui/src/lib/generated/uiRouteMap.ts``. It also refreshes the table of pages in
``docs/explanation/features/V2_CLASSIC_PAGE_PARITY.md`` between its generated markers, so the
document lists the registry as it is rather than as someone last remembered it.

The output is deterministic, and ``--check`` exits non-zero when either committed file is stale,
which ``functional_tests/test_ui_route_parity_registry.py`` relies on.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[1]
APP_ROOT = REPO_ROOT / "application" / "single_app"
DEFAULT_INPUT_PATH = APP_ROOT / "ui_route_map.json"
DEFAULT_OUTPUT_PATH = REPO_ROOT / "application" / "v2_ui" / "src" / "lib" / "generated" / "uiRouteMap.ts"
DEFAULT_DOC_PATH = REPO_ROOT / "docs" / "explanation" / "features" / "V2_CLASSIC_PAGE_PARITY.md"

DOC_BEGIN = (
    "<!-- ui-route-map:begin (generated by scripts\\build_ui_route_map.py from "
    "application\\single_app\\ui_route_map.json; do not edit by hand) -->"
)
DOC_END = "<!-- ui-route-map:end -->"
DOC_BLOCK_RE = re.compile(r"<!-- ui-route-map:begin.*?-->.*?<!-- ui-route-map:end -->", re.DOTALL)

# ui_routing is pure Python (no Flask, settings or network), so the script can share its
# status vocabulary and its validation instead of keeping a second copy of either.
sys.path.insert(0, str(APP_ROOT))
import ui_routing  # noqa: E402

GENERATED_HEADER = (
    "// uiRouteMap.ts\n"
    "// Generated by scripts\\build_ui_route_map.py from application\\single_app\\ui_route_map.json"
    " -- do not edit by hand.\n"
    "// Regenerate with: python scripts\\build_ui_route_map.py\n"
)

TYPES_BLOCK = """//
// Every classic (server-rendered) page route and the V2 route that replaces it, as data. The
// server reads the same file (ui_routing.py) for the classic to V2 redirect; V2 reads this copy
// for "open this page in classic". Only native, alias and partial rows resolve: a gap row
// names a V2 route that is planned but not built, and the other statuses have no V2 page.
// docs\\explanation\\features\\V2_CLASSIC_PAGE_PARITY.md describes the schema.

/** How far V2 has replaced a classic route. */
export type UiRouteStatus =
    | 'native'
    | 'alias'
    | 'partial'
    | 'gap'
    | 'standalone'
    | 'deliberate'
    | 'dead'
    | 'api_surface';

/** How one classic query key crosses to V2: renamed (with its values translated), or turned into a route segment. */
export interface UiRouteQueryRule {
    /** The V2 query key. */
    to?: string;
    /** Classic value to V2 value. A value that is not listed is not carried. */
    values?: Readonly<Record<string, string>>;
    /** The value must be a same-site path. */
    local_path?: boolean;
    /** Classic value to a route segment appended to the V2 path, such as '/tags'. */
    path?: Readonly<Record<string, string>>;
}

/** What a classic URL fragment becomes in V2: a route segment, query values, or both. */
export interface UiRouteHashRule {
    path?: string;
    query?: Readonly<Record<string, string>>;
}

export interface UiRouteEntry {
    /** Stable kebab-case id. */
    key: string;
    /** The Flask rule, such as '/groups/<group_id>'. */
    classic: string;
    methods: readonly string[];
    /** A request carrying all of these query pairs is never redirected (for example the embed frame V2 loads). */
    classic_only_query?: Readonly<Record<string, string>>;
    status: UiRouteStatus;
    /** The React Router path, relative to the /v2 basename, or null when V2 has no page for it. */
    v2: string | null;
    /** Query values the row always adds (an alias row's tab). */
    v2_query?: Readonly<Record<string, string>>;
    /** Other V2 routes that are the same classic page; used when going from V2 to classic. */
    v2_subroutes?: readonly string[];
    /** Values a V2 parameter must never take because they are other V2 pages. */
    v2_reserved?: Readonly<Record<string, readonly string[]>>;
    /** Classic placeholder to V2 parameter. */
    path_params?: Readonly<Record<string, string>>;
    /** Classic query key to what it becomes in V2. */
    query_map?: Readonly<Record<string, string | UiRouteQueryRule>>;
    /** Classic URL fragment to what it becomes in V2. */
    hash_map?: Readonly<Record<string, UiRouteHashRule>>;
    /** The classic templates the route renders. */
    templates?: readonly string[];
    /** For alias rows: the classic page the route redirects to. */
    alias_target?: string;
    /** The plan phase that closes a gap or a partial row. */
    plan_ref?: string;
    notes?: string;
}
"""

IDENTIFIER_RE = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")
INLINE_LIMIT = 108
INDENT = "    "


def format_string(value: str) -> str:
    """Render a single-quoted TypeScript string literal."""
    pieces = []
    for char in value:
        code = ord(char)
        if char == "\\":
            pieces.append("\\\\")
        elif char == "'":
            pieces.append("\\'")
        elif char == "\n":
            pieces.append("\\n")
        elif code < 0x20 or code >= 0x7F:
            pieces.append(f"\\u{{{code:x}}}")
        else:
            pieces.append(char)
    return "'" + "".join(pieces) + "'"


def format_key(key: str) -> str:
    return key if IDENTIFIER_RE.fullmatch(key) else format_string(key)


def format_inline(value: Any) -> str:
    """Render a value on one line."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return format_string(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(format_inline(item) for item in value) + "]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        return "{ " + ", ".join(f"{format_key(key)}: {format_inline(item)}" for key, item in value.items()) + " }"
    raise TypeError(f"Cannot render {type(value).__name__} as TypeScript.")


def format_value(value: Any, depth: int, prefix_length: int) -> str:
    """Render a value, on one line when it fits and indented across lines when it does not."""
    inline = format_inline(value)
    if not isinstance(value, (list, dict)) or not value:
        return inline
    simple = all(not isinstance(item, (list, dict)) for item in (value.values() if isinstance(value, dict) else value))
    if simple and prefix_length + len(inline) <= INLINE_LIMIT:
        return inline

    inner = INDENT * (depth + 1)
    closing = INDENT * depth
    if isinstance(value, list):
        lines = [f"{inner}{format_value(item, depth + 1, len(inner))}," for item in value]
        return "[\n" + "\n".join(lines) + f"\n{closing}]"
    lines = []
    for key, item in value.items():
        name = f"{format_key(key)}: "
        lines.append(f"{inner}{name}{format_value(item, depth + 1, len(inner) + len(name))},")
    return "{\n" + "\n".join(lines) + f"\n{closing}}}"


def render_typescript(route_map: ui_routing.UiRouteMap) -> str:
    """Render the whole generated module for a validated route map."""
    statuses = ", ".join(format_string(status) for status in ui_routing.RESOLVABLE_STATUSES)
    lines = [
        GENERATED_HEADER + TYPES_BLOCK,
        f"export const UI_ROUTE_MAP_SCHEMA_VERSION = {ui_routing.UI_ROUTE_MAP_SCHEMA_VERSION};",
        "",
        "/** The router basename V2 is served under. */",
        f"export const UI_ROUTE_V2_BASE_PATH = {format_string(ui_routing.V2_BASE_PATH)};",
        "",
        "/** The statuses whose rows have a V2 page to go to. */",
        f"export const UI_ROUTE_RESOLVABLE_STATUSES: readonly UiRouteStatus[] = [{statuses}];",
        "",
        "export const UI_ROUTE_MAP: readonly UiRouteEntry[] = [",
    ]
    for row in route_map.to_rows():
        lines.append(f"{INDENT}{format_value(row, 1, len(INDENT))},")
    lines.append("];")
    return "\n".join(lines) + "\n"


def render_doc_block(route_map: ui_routing.UiRouteMap) -> str:
    """Render the page table the feature document embeds, so the document cannot go stale."""
    counts = Counter(route.status for route in route_map.routes)
    summary = ", ".join(f"{counts[status]} {status}" for status in ui_routing.ROUTE_STATUSES if counts[status])
    lines = [
        DOC_BEGIN,
        "",
        f"{len(route_map.routes)} classic routes: {summary}.",
        "",
        "| Classic route | Methods | Status | V2 route | Plan | Key |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for route in route_map.routes:
        v2 = "-"
        if route.v2 is not None:
            query = "&".join(f"{name}={value}" for name, value in route.v2_query.items())
            v2 = f"`{route.v2}{'?' + query if query else ''}`"
        lines.append(
            f"| `{route.classic}` | {', '.join(route.methods)} | {route.status} | {v2} | {route.plan_ref or '-'} | `{route.key}` |"
        )
    lines += ["", DOC_END]
    return "\n".join(lines)


def replace_doc_block(document: str, block: str) -> str | None:
    """Swap the generated block in a document; None when the markers are missing or repeated."""
    matches = list(DOC_BLOCK_RE.finditer(document))
    if len(matches) != 1:
        return None
    match = matches[0]
    return document[:match.start()] + block + document[match.end():]


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description="Build the V2 TypeScript copy of the classic to V2 route map and refresh the page table in its feature document.",
    )
    parser.add_argument("--check", action="store_true", help="Exit non-zero if the TypeScript file or the document table is out of date.")
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT_PATH, help="Registry JSON path.")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_PATH, help="Destination TypeScript path.")
    parser.add_argument("--doc", type=Path, default=DEFAULT_DOC_PATH, help="Feature document whose generated table is refreshed.")
    return parser.parse_args()


def resolve(path: Path) -> Path:
    return path if path.is_absolute() else REPO_ROOT / path


def main() -> int:
    """Run the generator."""
    args = parse_args()
    input_path = resolve(args.input)
    output_path = resolve(args.output)
    doc_path = resolve(args.doc)

    try:
        route_map = ui_routing.load_ui_route_map(input_path)
    except ui_routing.UiRouteMapError as error:
        print(str(error), file=sys.stderr)
        return 2
    rendered = render_typescript(route_map)

    if not doc_path.is_file():
        print(f"The feature document is missing: {doc_path}", file=sys.stderr)
        return 2
    document = doc_path.read_text(encoding="utf-8")
    new_document = replace_doc_block(document, render_doc_block(route_map))
    if new_document is None:
        print(
            f"{doc_path} needs exactly one generated table between the markers\n{DOC_BEGIN}\nand\n{DOC_END}",
            file=sys.stderr,
        )
        return 2

    if args.check:
        existing = output_path.read_text(encoding="utf-8") if output_path.exists() else ""
        stale = []
        if existing != rendered:
            stale.append(str(output_path))
        if document != new_document:
            stale.append(str(doc_path))
        if stale:
            print(
                "UI route map output is out of date: " + ", ".join(stale) + "\n"
                "Regenerate it with: python scripts\\build_ui_route_map.py",
                file=sys.stderr,
            )
            return 1
        print(f"UI route map outputs are in sync: {output_path} and {doc_path}")
        return 0

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(rendered, encoding="utf-8", newline="\n")
    if document != new_document:
        doc_path.write_text(new_document, encoding="utf-8", newline="\n")
    counts = Counter(route.status for route in route_map.routes)
    summary = ", ".join(f"{status}: {counts[status]}" for status in ui_routing.ROUTE_STATUSES if counts[status])
    print(f"Wrote UI route map TypeScript and document table ({len(route_map.routes)} routes; {summary}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
